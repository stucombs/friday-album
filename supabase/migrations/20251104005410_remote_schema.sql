CREATE OR REPLACE FUNCTION "public"."random_album"("backlog" boolean) RETURNS SETOF "record"
    LANGUAGE "sql"
    AS $$select jsonb_build_object(
    'id', a.id,
    'title', a.title,
    'artist', a.artist,
    'release_year', a.release_year,
    'genre', jsonb_build_object(
      'id', g.id,
      'name', g.name
    ),
    'am_link', a.am_link,
    'spotify_link', a.spotify_link,
    'cover_url', a.cover_url
  ) as album
  from albums a
  inner join genre g on g.id = a.genre_id
  where archived = backlog
  order by random()
  limit 1;$$;
